#!/usr/bin/env bash

# Build Rocq together with some of the CI projects of _build_ci in a single
# (composed) dune build from the Rocq root, using the rocq dune language.
#
# Usage: ./build.sh [-n] [target...] [-- dune-args...]
#
# Targets (all by default): stdlib equations elpi hb vsrocq vsrocq-client rocq_lsp
# (a ci- prefix is accepted, e.g. ci-elpi). Rocq itself is always built.
# Missing CI projects are downloaded as `make ci-<target>` would do.
#
#  -n            only set up the dune files, do not build
#  -- args...    extra arguments passed to dune build (e.g. -- --profile release)
#
# Everything ends up in _build/install/default (bin/vsrocqtop,
# lib/coq/user-contrib/{elpi,HB}, ...); the client is packaged as
# _build_ci/vsrocq/client/vsrocq-*.vsix.
#
# Setup performed on the (untracked or CI-cloned) sources:
# - theories/{Corelib,Ltac2}/dune are replaced by their dune.disabled
#   rocq.theory versions, so that Corelib is a dune theory other projects can
#   depend on (`make world` / dunestrap puts the generated rules back, the next
#   ./build.sh switches again);
# - elpi's dune files are ported from (using coq 0.8) to (using rocq 0.11);
# - dune files for HB are added (it is built with coq_makefile upstream).
# The root dune file lists the _build_ci directories in the composed build.

set -e

ALL_TARGETS="stdlib equations elpi hb vsrocq vsrocq-client rocq_lsp"

cd "$(dirname "$0")"
ROOT=$PWD
CI_BUILD_DIR=$ROOT/_build_ci

setup_only=
targets=()
dune_args=()
while [ $# -gt 0 ]; do
  case "$1" in
    -n) setup_only=1 ;;
    -h|--help) sed -n '3,/^$/s/^# \{0,1\}//p' "$0"; exit 0 ;;
    --) shift; dune_args=("$@"); break ;;
    *) t=${1#ci-}
       case " $ALL_TARGETS " in
         *" $t "*) targets+=("$t") ;;
         *) echo "Unknown target $1 (known: $ALL_TARGETS)" >&2; exit 1 ;;
       esac ;;
  esac
  shift
done
[ ${#targets[@]} -eq 0 ] && read -r -a targets <<< "$ALL_TARGETS"

has_target () { case " ${targets[*]} " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

eval "$(opam env --switch=rocq-dev --set-switch)"

# CI project directory and download name of a target
ci_dir () { case "$1" in hb) echo hierarchy_builder ;; vsrocq-client) echo vsrocq ;; *) echo "$1" ;; esac; }
ci_name () { case "$1" in vsrocq-client) echo vsrocq ;; *) echo "$1" ;; esac; }

for t in "${targets[@]}"; do
  # CI projects the target needs in the workspace
  case "$t" in
    hb) deps="elpi hb" ;;
    equations) deps="stdlib equations" ;;
    *) deps=$t ;;
  esac
  for d in $deps; do
    if [ ! -d "$CI_BUILD_DIR/$(ci_dir "$d")" ]; then
      DOWNLOAD_ONLY=1 ./dev/ci/ci-wrapper.sh "$(ci_name "$d")"
    fi
  done
done

for lib in Corelib Ltac2; do
  cmp -s "theories/$lib/dune.disabled" "theories/$lib/dune" ||
    cp "theories/$lib/dune.disabled" "theories/$lib/dune"
done

if [ -d "$CI_BUILD_DIR/elpi" ]; then
  ( cd "$CI_BUILD_DIR/elpi"
    git ls-files -z dune-project '*/dune-project' dune '*/dune' |
      xargs -0 perl -pi -e '
        s/^\(lang dune 3\.\d+\)/(lang dune 3.21)/;
        s/^\(using coq 0\.8\)/(using rocq 0.11)/;
        s/\(coq\.(theory|pp)\b/(rocq.$1/g;
        s/%\{coq:/%{rocq:/g;
        s/^(\s*)\(coq \(flags/$1(rocq (flags/;'
  )
fi

if [ -d "$CI_BUILD_DIR/hierarchy_builder" ]; then
  hb=$CI_BUILD_DIR/hierarchy_builder
  mkdir -p "$hb/dune-theory/common"
  cat > "$hb/dune-project" <<'EOF'
(lang dune 3.21)
; generated by rocq's build.sh
(using rocq 0.11)
(name rocq-hierarchy-builder)
EOF
  cat > "$hb/dune-theory/dune" <<'EOF'
; generated by rocq's build.sh: dune build of HB (upstream uses coq_makefile).
; The theory is built here rather than in HB/ so that structures.v can be a
; generated copy depending on the elpi sources: rocq dep does not see
; Elpi Accumulate File, and elpi finds the files through the HB loadpath,
; i.e. this directory.
(rocq.theory
 (name HB)
 (package rocq-hierarchy-builder)
 (theories elpi elpi.apps.locker)
 (flags :standard
  -w -elpi.accumulate-syntax
  -w +elpi.typecheck
  -w -elpi.typecheck-syntax
  -w -elpi.flex-clause))

(include_subdirs qualified)

(copy_files (files ../HB/*.elpi))

(rule
 (deps
  (glob_files *.elpi)
  (glob_files common/*.elpi))
 (action (copy ../HB/structures.v structures.v)))

(install
 (files
  (glob_files (*.elpi with_prefix coq/user-contrib/HB))
  (glob_files (common/*.elpi with_prefix coq/user-contrib/HB/common)))
 (section lib_root)
 (package rocq-hierarchy-builder))
EOF
  cat > "$hb/dune-theory/common/dune" <<'EOF'
; generated by rocq's build.sh
(copy_files (files ../../HB/common/*.elpi))
EOF
fi

[ -n "$setup_only" ] && exit 0

dune_targets=(@@default)
for t in "${targets[@]}"; do
  case "$t" in
    stdlib) dune_targets+=(_build_ci/stdlib/rocq-stdlib.install) ;;
    equations) dune_targets+=(_build_ci/equations/rocq-equations.install) ;;
    elpi) dune_targets+=(_build_ci/elpi/rocq-elpi.install) ;;
    hb) dune_targets+=(_build_ci/hierarchy_builder/rocq-hierarchy-builder.install) ;;
    vsrocq) dune_targets+=(_build_ci/vsrocq/language-server/vsrocq-language-server.install) ;;
    rocq_lsp) dune_targets+=(_build_ci/rocq_lsp/coq-lsp.install) ;;
  esac
done

if has_target vsrocq; then
  # vsrocq generates its dune files from the version of the rocq in PATH
  dune build "${dune_args[@]}" rocq-runtime.install
  ( export PATH="$ROOT/_build/install/default/bin:$PATH"
    cd "$CI_BUILD_DIR/vsrocq/language-server" && make dune-files )
fi

dune build "${dune_args[@]}" "${dune_targets[@]}"

if has_target vsrocq-client; then
  ( cd "$CI_BUILD_DIR/vsrocq/client"
    if [ ! -f node_modules/.package-lock.json ] ||
       [ package-lock.json -nt node_modules/.package-lock.json ]; then
      npm ci --no-audit --no-fund
    fi
    # rebuild only if some source (or the installed node_modules) is newer
    # than the package
    vsix=vsrocq-$(node -p 'require("./package.json").version').vsix
    if [ -f "$vsix" ] &&
       [ -z "$(find . -path ./node_modules -prune -o -newer "$vsix" -type f -print -quit)" ] &&
       [ ! node_modules/.package-lock.json -nt "$vsix" ]; then
      echo "$CI_BUILD_DIR/vsrocq/client/$vsix is up to date"
    else
      npm run build --workspaces
      npx vsce package --no-dependencies
    fi
  )
fi
